/// Full nested residual-recovery SpGEMM corresponding to Algorithm 1 in Graia
/// (2026), parameterized by a recovery backend.
///
/// `k_bound` is the promise K >= nnz(A*B). With `RecoveryBackend::Identity`,
/// this is an exact implementation of the nested update logic using valid
/// identity recovery pairs. `RecoveryBackend::Signature` uses a practical
/// deterministic hash graph. `RecoveryBackend::Guv` uses the explicit
/// Parvaresh-Vardy/GUV graph from Bennett et al. Appendix A. When a backend's
/// `guaranteed_correction` flag is enabled, an exact identity residual pass is
/// appended as an implementation-validation fallback.
pub fn nested_spgemm(
    a: &CsrMatrix,
    b: &CsrMatrix,
    k_bound: usize,
    backend: RecoveryBackend,
) -> (CsrMatrix, NestedSpGemmStats) {
    nested_spgemm_with_options(a, b, k_bound, backend, NestedOptions::default())
}

/// Backward-compatible v0.5 entry point with only a rectangular-kernel policy.
pub fn nested_spgemm_with_policy(
    a: &CsrMatrix,
    b: &CsrMatrix,
    k_bound: usize,
    backend: RecoveryBackend,
    rectangular_policy: RectangularPolicy,
) -> (CsrMatrix, NestedSpGemmStats) {
    nested_spgemm_with_options(
        a,
        b,
        k_bound,
        backend,
        NestedOptions {
            rectangular_policy,
            ..NestedOptions::default()
        },
    )
}

/// v0.7 engineering entry point. The theorem-pure behavior is obtained with
/// `NestedOptions::default()`. Practical scheduling and support masking are
/// explicitly opt-in at the library level; the benchmark CLI enables them by
/// default so their effect is visible.
pub fn nested_spgemm_with_options(
    a: &CsrMatrix,
    b: &CsrMatrix,
    k_bound: usize,
    backend: RecoveryBackend,
    options: NestedOptions,
) -> (CsrMatrix, NestedSpGemmStats) {
    assert_eq!(a.cols, b.rows, "incompatible matrix dimensions");
    let r = a.rows;
    let c = b.cols;
    let k = k_bound.min(r.saturating_mul(c));

    if r == 0 || c == 0 || k == 0 {
        return (CsrMatrix::zeros(r, c), NestedSpGemmStats::default());
    }

    let schedule = paper_schedule(r, c, k);
    let mut d = SparseColumns::zeros(r, c);
    let mut d_version = 0u64;
    let mut stats = NestedSpGemmStats::default();
    let mut support_mask: Option<Vec<bool>> = None;
    let mut scheduler_target_q = 0usize;
    let fingerprint = options.residual_fingerprint.map(|cfg| {
        let start = Instant::now();
        let fp = ResidualFingerprint::new(a, b, cfg);
        stats.fingerprint_setup_time = start.elapsed();
        stats.fingerprint = Some(FingerprintStats {
            lanes: fp.lanes(),
            seed: fp.seed,
            ..FingerprintStats::default()
        });
        fp
    });

    // v0.7 cache hierarchy:
    //   recovery matrix -> H*A / B*G^T -> H*A*B*G^T -> residual W for one D version.
    // Round-reseeded Signature/Moment matrices are not cached, while identity/GUV
    // factors and products are reused. A support-masked B factor is deliberately
    // round-local because the mask changes as columns are recovered.
    let mut recovery_matrix_cache: HashMap<RecoveryMatrixKey, BinaryRecoveryMatrix> = HashMap::new();
    let mut left_factor_cache: HashMap<RecoveryMatrixKey, Arc<PreparedFactor>> = HashMap::new();
    let mut right_factor_cache: HashMap<RecoveryMatrixKey, Arc<PreparedFactor>> = HashMap::new();
    let mut product_cache: HashMap<(RecoveryMatrixKey, RecoveryMatrixKey), CachedProduct> = HashMap::new();
    let mut residual_cache: HashMap<ResidualCacheKey, CachedResidual> = HashMap::new();

    let mut schedule_pos = 0usize;
    while schedule_pos < schedule.len() {
        let params = schedule[schedule_pos].clone();
        schedule_pos += 1;

        if options.practical_scheduler && scheduler_target_q > 0 && params.q < scheduler_target_q {
            stats.scheduler_skipped_rounds += 1;
            continue;
        }

        let (h, h_matrix_cache_hit, h_key) = build_recovery_matrix_cached(
            &mut recovery_matrix_cache,
            r,
            params.q,
            &backend,
            0x4849_4E4E_4552,
            params.i,
        );
        let (g, g_matrix_cache_hit, g_key) = build_recovery_matrix_cached(
            &mut recovery_matrix_cache,
            c,
            params.p,
            &backend,
            0x4F55_5445_52,
            params.i,
        );

        let active_mask = if options.masked_residual && g.is_identity() {
            support_mask.as_ref().filter(|m| m.iter().any(|&x| x))
        } else {
            None
        };
        let masked_residual = active_mask.is_some();
        let active_mask_columns = active_mask
            .map(|m| m.iter().filter(|&&x| x).count())
            .unwrap_or(c);

        let pair_key = (h_key.clone(), g_key.clone());
        let residual_key = ResidualCacheKey {
            h: h_key.clone(),
            g: g_key.clone(),
            d_version,
        };
        let cache_pair = !masked_residual && h_key.cacheable() && g_key.cacheable();

        let mut left_time = Duration::default();
        let mut right_time = Duration::default();
        let mut rectangular_time = Duration::default();
        let mut residual_measure_time = Duration::default();
        let mut product_cache_hit = false;
        let mut residual_cache_hit = false;

        // Option rather than a dummy false assignment avoids the v0.5 compiler
        // warnings about values that were always overwritten before being read.
        let ha_cache_hit: bool;
        let bgt_cache_hit: bool;

        let (w, rectangular_stats) = if masked_residual {
            let (ha, hit, elapsed) = get_or_build_factor(
                &mut left_factor_cache,
                &h_key,
                || left_recovery_sketch(a, &h),
            );
            ha_cache_hit = hit;
            left_time = elapsed;

            let start = Instant::now();
            let bgt = PreparedFactor::new(right_recovery_sketch_masked(b, &g, active_mask.unwrap()));
            right_time = start.elapsed();
            bgt_cache_hit = false;

            let start = Instant::now();
            let (hcgt, rect_stats) = adaptive_matmul_prepared(&ha, &bgt, options.rectangular_policy);
            rectangular_time = start.elapsed();

            let start = Instant::now();
            let hdgt = d.two_sided_measure_masked(&h, &g, active_mask.unwrap());
            let mut residual = hcgt;
            sub_assign_dense(&mut residual, &hdgt);
            residual_measure_time = start.elapsed();
            (Arc::new(residual), rect_stats)
        } else if cache_pair {
            if let Some(cached) = residual_cache.get(&residual_key) {
                residual_cache_hit = true;
                product_cache_hit = product_cache.contains_key(&pair_key);
                ha_cache_hit = left_factor_cache.contains_key(&h_key);
                bgt_cache_hit = right_factor_cache.contains_key(&g_key);
                (cached.matrix.clone(), cached.product_stats.clone())
            } else {
                let (hcgt, rect_stats) = if let Some(cached) = product_cache.get(&pair_key) {
                    product_cache_hit = true;
                    ha_cache_hit = left_factor_cache.contains_key(&h_key);
                    bgt_cache_hit = right_factor_cache.contains_key(&g_key);
                    (cached.matrix.clone(), cached.stats.clone())
                } else {
                    let (ha, hit, elapsed) = get_or_build_factor(
                        &mut left_factor_cache,
                        &h_key,
                        || left_recovery_sketch(a, &h),
                    );
                    ha_cache_hit = hit;
                    left_time = elapsed;

                    let (bgt, hit, elapsed) = get_or_build_factor(
                        &mut right_factor_cache,
                        &g_key,
                        || right_recovery_sketch(b, &g),
                    );
                    bgt_cache_hit = hit;
                    right_time = elapsed;

                    let start = Instant::now();
                    let (product, rect_stats) = adaptive_matmul_prepared(&ha, &bgt, options.rectangular_policy);
                    rectangular_time = start.elapsed();
                    let product = Arc::new(product);
                    product_cache.insert(
                        pair_key.clone(),
                        CachedProduct {
                            matrix: product.clone(),
                            stats: rect_stats.clone(),
                        },
                    );
                    (product, rect_stats)
                };

                let start = Instant::now();
                let hdgt = d.two_sided_measure(&h, &g);
                let mut residual = (*hcgt).clone();
                sub_assign_dense(&mut residual, &hdgt);
                residual_measure_time = start.elapsed();
                let residual = Arc::new(residual);
                residual_cache.insert(
                    residual_key,
                    CachedResidual {
                        matrix: residual.clone(),
                        product_stats: rect_stats.clone(),
                    },
                );
                (residual, rect_stats)
            }
        } else {
            let (ha, hit, elapsed) = get_or_build_factor(
                &mut left_factor_cache,
                &h_key,
                || left_recovery_sketch(a, &h),
            );
            ha_cache_hit = hit;
            left_time = elapsed;

            let (bgt, hit, elapsed) = get_or_build_factor(
                &mut right_factor_cache,
                &g_key,
                || right_recovery_sketch(b, &g),
            );
            bgt_cache_hit = hit;
            right_time = elapsed;

            let start = Instant::now();
            let (hcgt, rect_stats) = adaptive_matmul_prepared(&ha, &bgt, options.rectangular_policy);
            rectangular_time = start.elapsed();

            let start = Instant::now();
            let hdgt = d.two_sided_measure(&h, &g);
            let mut residual = hcgt;
            sub_assign_dense(&mut residual, &hdgt);
            residual_measure_time = start.elapsed();
            (Arc::new(residual), rect_stats)
        };

        let rectangular_kernel = rectangular_stats
            .kernel
            .expect("adaptive rectangular multiplication did not select a kernel");
        let w_nnz = w.nnz();

        // A zero identity residual is global only when no support mask was used.
        let certified_zero_residual = !masked_residual
            && h.is_identity()
            && g.is_identity()
            && w_nnz == 0;

        let start = Instant::now();
        let outer = if certified_zero_residual {
            Vec::new()
        } else {
            safe_decode_product(&g, w.as_ref(), params.p)
        };
        let outer_recovered = outer.len();

        // Identity G exposes concrete output-column ids. Use the first such
        // observation as a practical superset mask; subsequent rounds only
        // remove columns that have been accepted by the inner decoder.
        if options.masked_residual && g.is_identity() && support_mask.is_none() && !outer.is_empty() {
            let mut mask = vec![false; c];
            for (j, _) in &outer {
                mask[*j] = true;
            }
            support_mask = Some(mask);
        }

        let mut inner_updates = 0usize;
        let mut round_changed_d = false;
        let allow_mask_removal = h.is_identity() || matches!(&h, BinaryRecoveryMatrix::Moment(_));

        for (j, xi) in outer {
            let z = safe_decode_scalar(&h, &xi, params.q);
            if !z.is_empty() {
                round_changed_d |= d.add_to_column(j, &z);
                inner_updates += 1;
                if options.masked_residual && allow_mask_removal {
                    if let Some(mask) = support_mask.as_mut() {
                        mask[j] = false;
                    }
                }
            }
        }
        if round_changed_d {
            d_version = d_version.wrapping_add(1);
            residual_cache.clear();
        }
        let decode_time = start.elapsed();

        let remaining_mask_columns = support_mask
            .as_ref()
            .map(|m| m.iter().filter(|&&x| x).count())
            .unwrap_or(0);

        // Practical q jump: if identity G showed m live columns, an exact-K
        // benchmark implies average remaining column sparsity K_remaining/m.
        // Jump to the next power of two rather than spending a round below that.
        if options.practical_scheduler && g.is_identity() {
            let observed = remaining_mask_columns.max(if support_mask.is_none() { outer_recovered } else { 0 });
            if observed > 0 {
                let scheduler_k = options.scheduler_k_hint.unwrap_or(k);
                let remaining_bound = scheduler_k.saturating_sub(d.nnz()).max(1);
                let avg = remaining_bound.saturating_add(observed - 1) / observed;
                let target = avg.max(1).next_power_of_two().min(r.max(1));
                scheduler_target_q = scheduler_target_q.max(target);
            }
        }

        // Full identity measurements are globally complete only without a mask.
        let complete_identity_recovery = !masked_residual
            && h.is_identity()
            && g.is_identity()
            && outer_recovered > 0
            && inner_updates == outer_recovered;

        let rectangular_scalar_multiplications = if product_cache_hit || residual_cache_hit {
            0
        } else {
            rectangular_stats.scalar_multiplications
        };

        stats.rounds.push(NestedRoundStats {
            params: params.clone(),
            h_rows: h.rows(),
            g_rows: g.rows(),
            h_kind: h.kind(),
            g_kind: g.kind(),
            w_nnz,
            outer_recovered,
            inner_updates,
            d_nnz_after: d.nnz(),
            left_time,
            right_time,
            rectangular_time,
            rectangular_kernel,
            rectangular_scalar_multiplications,
            rectangular_candidate_products: rectangular_stats.sparse_candidate_products,
            ha_density: rectangular_stats.a_density,
            bgt_density: rectangular_stats.b_density,
            h_matrix_cache_hit,
            g_matrix_cache_hit,
            ha_cache_hit,
            bgt_cache_hit,
            product_cache_hit,
            residual_cache_hit,
            masked_residual,
            active_mask_columns,
            scheduler_target_q,
            residual_measure_time,
            decode_time,
        });

        if certified_zero_residual {
            stats.deterministic_verified = true;
            stats.terminated_early = true;
            stats.termination_reason = Some(format!(
                "identity residual certificate W=0 at round {}",
                params.i
            ));
            break;
        }

        if complete_identity_recovery {
            stats.deterministic_verified = true;
            stats.terminated_early = true;
            stats.termination_reason = Some(format!(
                "complete identity residual recovery at round {}",
                params.i
            ));
            break;
        }

        // v0.7: an exhausted observed support can be certified without exact K
        // by an independent bilinear fingerprint of AB-D. A failed certificate
        // discards the mask so later rounds can rediscover residual support.
        let mask_exhausted = support_mask
            .as_ref()
            .map(|m| !m.iter().any(|&x| x))
            .unwrap_or(false);
        if options.masked_residual && mask_exhausted {
            if let Some(fp) = fingerprint.as_ref() {
                let start = Instant::now();
                let candidate = d.to_csr();
                let passed = fp.verifies(&candidate);
                stats.fingerprint_check_time += start.elapsed();
                if let Some(fps) = stats.fingerprint.as_mut() {
                    fps.checks += 1;
                    if passed { fps.passes += 1; } else { fps.failures += 1; }
                }
                if passed {
                    stats.fingerprint_verified = true;
                    stats.terminated_early = true;
                    stats.termination_reason = Some(format!(
                        "residual fingerprint certified AB-D=0 in round {}",
                        params.i
                    ));
                    break;
                } else {
                    // A failed independent certificate overrides support/nnz
                    // heuristics: rediscover residual columns on later rounds.
                    support_mask = None;
                }
            }
        }

        // In exact-K benchmark mode, exhausting the observed support with exactly
        // K verified/accepted nonzeros is a useful practical stop condition.
        if options.exact_k_bound
            && options.masked_residual
            && support_mask.as_ref().map(|m| !m.iter().any(|&x| x)).unwrap_or(false)
            && d.nnz() == k
        {
            stats.deterministic_verified = true;
            stats.terminated_early = true;
            stats.termination_reason = Some(format!(
                "observed residual support exhausted at exact K in round {}",
                params.i
            ));
            break;
        }

        // If the observed mask was exhausted but K says entries remain, discard
        // the mask so a later full round can discover omitted support.
        if options.exact_k_bound
            && support_mask.as_ref().map(|m| !m.iter().any(|&x| x)).unwrap_or(false)
            && d.nnz() < k
        {
            support_mask = None;
        }
    }

    // Final fingerprint opportunity even when the support mask did not become
    // empty on the last scheduled round. This is especially useful when K was
    // only an estimate and the decoder nevertheless reconstructed the product.
    if !stats.fingerprint_verified && !stats.deterministic_verified {
        if let Some(fp) = fingerprint.as_ref() {
            let start = Instant::now();
            let candidate = d.to_csr();
            let passed = fp.verifies(&candidate);
            stats.fingerprint_check_time += start.elapsed();
            if let Some(fps) = stats.fingerprint.as_mut() {
                fps.checks += 1;
                if passed { fps.passes += 1; } else { fps.failures += 1; }
            }
            if passed {
                stats.fingerprint_verified = true;
                stats.terminated_early = true;
                stats.termination_reason = Some("final residual fingerprint certified AB-D=0".to_string());
            }
        }
    }

    let guaranteed_correction = match &backend {
        RecoveryBackend::Identity => false,
        RecoveryBackend::Signature(cfg) => cfg.guaranteed_correction,
        RecoveryBackend::Moment(cfg) => cfg.guaranteed_correction,
        RecoveryBackend::Guv(cfg) => cfg.guaranteed_correction,
    };
    let exact_k_safety = options.masked_residual && options.exact_k_bound && d.nnz() != k;
    let fingerprint_safety = options.residual_fingerprint.is_some()
        && (options.fingerprint_failure_correction || options.exact_k_bound)
        && !stats.fingerprint_verified
        && !stats.deterministic_verified;
    if guaranteed_correction || exact_k_safety || fingerprint_safety {
        let start = Instant::now();
        let h = BinaryRecoveryMatrix::identity(r);
        let g = BinaryRecoveryMatrix::identity(c);

        let ha = left_recovery_sketch(a, &h);
        let bgt = right_recovery_sketch(b, &g);
        let mut residual = dense_matmul(&ha, &bgt);
        let d_measure = d.two_sided_measure(&h, &g);
        sub_assign_dense(&mut residual, &d_measure);

        let mut residual_columns = 0usize;
        let mut residual_nnz = 0usize;
        for j in 0..c {
            let mut col = Vec::new();
            for i in 0..r {
                let v = residual[(i, j)];
                if v != 0 {
                    col.push((i, v));
                }
            }
            if !col.is_empty() {
                residual_columns += 1;
                residual_nnz += col.len();
                d.add_to_column(j, &col);
            }
        }

        stats.correction_pass = Some(CorrectionPassStats {
            residual_columns,
            residual_nnz,
            elapsed: start.elapsed(),
        });
        stats.deterministic_verified = true;
    }

    (d.to_csr(), stats)
}

fn get_or_build_factor<F>(
    cache: &mut HashMap<RecoveryMatrixKey, Arc<PreparedFactor>>,
    key: &RecoveryMatrixKey,
    build: F,
) -> (Arc<PreparedFactor>, bool, Duration)
where
    F: FnOnce() -> DenseMatrix,
{
    if key.cacheable() {
        if let Some(existing) = cache.get(key) {
            return (existing.clone(), true, Duration::default());
        }
    }

    let start = Instant::now();
    let matrix = Arc::new(PreparedFactor::new(build()));
    let elapsed = start.elapsed();
    if key.cacheable() {
        cache.insert(key.clone(), matrix.clone());
    }
    (matrix, false, elapsed)
}

fn build_recovery_matrix_cached(
    cache: &mut HashMap<RecoveryMatrixKey, BinaryRecoveryMatrix>,
    domain: usize,
    capacity: usize,
    backend: &RecoveryBackend,
    salt: u64,
    round: usize,
) -> (BinaryRecoveryMatrix, bool, RecoveryMatrixKey) {
    let capacity = capacity.clamp(1, domain);
    let hinted_key = recovery_matrix_key_hint(domain, capacity, backend, salt, round);
    if hinted_key.cacheable() {
        if let Some(existing) = cache.get(&hinted_key) {
            return (existing.clone(), true, hinted_key);
        }
    }

    let (built, actual_key) = build_recovery_matrix(domain, capacity, backend, salt, round);
    if actual_key.cacheable() {
        if let Some(existing) = cache.get(&actual_key) {
            return (existing.clone(), true, actual_key);
        }
        cache.insert(actual_key.clone(), built.clone());
    }
    (built, false, actual_key)
}

fn recovery_matrix_key_hint(
    domain: usize,
    capacity: usize,
    backend: &RecoveryBackend,
    salt: u64,
    round: usize,
) -> RecoveryMatrixKey {
    match backend {
        RecoveryBackend::Identity => RecoveryMatrixKey::Identity { domain },
        RecoveryBackend::Signature(cfg) => {
            let seed = cfg.seed
                ^ salt
                ^ (round as u64).wrapping_mul(0xA076_1D64_78BD_642F);
            let sig = SignatureRecovery::new(
                domain,
                capacity,
                cfg.degree,
                cfg.oversampling,
                seed,
            );
            if cfg.identity_fallback && sig.rows() >= domain {
                RecoveryMatrixKey::Identity { domain }
            } else {
                RecoveryMatrixKey::Signature {
                    domain,
                    capacity,
                    degree: cfg.degree,
                    oversampling_bits: cfg.oversampling.to_bits(),
                    seed,
                }
            }
        }
        RecoveryBackend::Moment(cfg) => {
            let seed = cfg.seed
                ^ salt
                ^ (round as u64).wrapping_mul(0xA076_1D64_78BD_642F);
            let moment = MomentRecovery::new(
                domain, capacity, cfg.degree, cfg.oversampling, seed,
            );
            if cfg.identity_fallback && moment.rows() >= domain {
                RecoveryMatrixKey::Identity { domain }
            } else {
                RecoveryMatrixKey::Moment {
                    domain,
                    capacity,
                    degree: cfg.degree,
                    oversampling_bits: cfg.oversampling.to_bits(),
                    seed,
                }
            }
        }
        RecoveryBackend::Guv(cfg) => {
            if capacity == 1 {
                return RecoveryMatrixKey::Identity { domain };
            }
            let estimated = GuvParameters::estimated_rows(
                domain,
                capacity,
                cfg.alpha,
                cfg.epsilon,
            );
            if cfg.identity_fallback && estimated >= domain {
                RecoveryMatrixKey::Identity { domain }
            } else {
                RecoveryMatrixKey::Guv {
                    domain,
                    capacity,
                    alpha_bits: cfg.alpha.to_bits(),
                    epsilon_bits: cfg.epsilon.to_bits(),
                }
            }
        }
    }
}

fn build_recovery_matrix(
    domain: usize,
    capacity: usize,
    backend: &RecoveryBackend,
    salt: u64,
    round: usize,
) -> (BinaryRecoveryMatrix, RecoveryMatrixKey) {
    match backend {
        RecoveryBackend::Identity => (
            BinaryRecoveryMatrix::identity(domain),
            RecoveryMatrixKey::Identity { domain },
        ),
        RecoveryBackend::Signature(cfg) => {
            let seed = cfg.seed
                ^ salt
                ^ (round as u64).wrapping_mul(0xA076_1D64_78BD_642F);
            let sig = SignatureRecovery::new(
                domain,
                capacity,
                cfg.degree,
                cfg.oversampling,
                seed,
            );
            if cfg.identity_fallback && sig.rows() >= domain {
                (
                    BinaryRecoveryMatrix::identity(domain),
                    RecoveryMatrixKey::Identity { domain },
                )
            } else {
                (
                    BinaryRecoveryMatrix::Signature(sig),
                    RecoveryMatrixKey::Signature {
                        domain,
                        capacity,
                        degree: cfg.degree,
                        oversampling_bits: cfg.oversampling.to_bits(),
                        seed,
                    },
                )
            }
        }
        RecoveryBackend::Moment(cfg) => {
            let seed = cfg.seed
                ^ salt
                ^ (round as u64).wrapping_mul(0xA076_1D64_78BD_642F);
            let moment = MomentRecovery::new(
                domain, capacity, cfg.degree, cfg.oversampling, seed,
            );
            if cfg.identity_fallback && moment.rows() >= domain {
                (
                    BinaryRecoveryMatrix::identity(domain),
                    RecoveryMatrixKey::Identity { domain },
                )
            } else {
                (
                    BinaryRecoveryMatrix::Moment(moment),
                    RecoveryMatrixKey::Moment {
                        domain,
                        capacity,
                        degree: cfg.degree,
                        oversampling_bits: cfg.oversampling.to_bits(),
                        seed,
                    },
                )
            }
        }
        RecoveryBackend::Guv(cfg) => {
            if capacity == 1 {
                return (
                    BinaryRecoveryMatrix::identity(domain),
                    RecoveryMatrixKey::Identity { domain },
                );
            }
            let estimated = GuvParameters::estimated_rows(
                domain,
                capacity,
                cfg.alpha,
                cfg.epsilon,
            );
            if cfg.identity_fallback && estimated >= domain {
                return (
                    BinaryRecoveryMatrix::identity(domain),
                    RecoveryMatrixKey::Identity { domain },
                );
            }
            let guv = GuvRecovery::new(domain, capacity, cfg.alpha, cfg.epsilon)
                .unwrap_or_else(|e| panic!("failed to construct explicit GUV recovery matrix: {e}"));
            if cfg.identity_fallback && guv.rows() >= domain {
                (
                    BinaryRecoveryMatrix::identity(domain),
                    RecoveryMatrixKey::Identity { domain },
                )
            } else {
                (
                    BinaryRecoveryMatrix::Guv(guv),
                    RecoveryMatrixKey::Guv {
                        domain,
                        capacity,
                        alpha_bits: cfg.alpha.to_bits(),
                        epsilon_bits: cfg.epsilon.to_bits(),
                    },
                )
            }
        }
    }
}

/// Compute H*A for any binary recovery matrix H without materializing H.
pub fn left_recovery_sketch(a: &CsrMatrix, h: &BinaryRecoveryMatrix) -> DenseMatrix {
    assert_eq!(h.domain(), a.rows);
    if h.is_identity() {
        return a.to_dense();
    }

    let mut out = DenseMatrix::zeros(h.rows(), a.cols);
    let rows_by_index: Vec<Vec<(usize, i64)>> =
        (0..h.domain()).map(|i| h.weighted_rows_for_index(i)).collect();
    for i in 0..a.rows {
        let measurement_rows = &rows_by_index[i];
        for (k, value) in a.row(i) {
            for &(mr, coeff) in measurement_rows {
                out[(mr, k)] += coeff * value;
            }
        }
    }
    out
}

/// Compute B*G^T for any binary recovery matrix G without materializing G.
pub fn right_recovery_sketch(b: &CsrMatrix, g: &BinaryRecoveryMatrix) -> DenseMatrix {
    assert_eq!(g.domain(), b.cols);
    if g.is_identity() {
        return b.to_dense();
    }

    let mut out = DenseMatrix::zeros(b.rows, g.rows());
    // Cache the column mapping once. In CSR traversal the same output column j
    // can occur in many B rows, so recomputing rows_for_index(j) inside the nnz
    // loop caused a large amount of hashing/allocation work in v0.4.
    let rows_by_column: Vec<Vec<(usize, i64)>> =
        (0..g.domain()).map(|j| g.weighted_rows_for_index(j)).collect();
    for k in 0..b.rows {
        for (j, value) in b.row(k) {
            for &(mr, coeff) in &rows_by_column[j] {
                out[(k, mr)] += value * coeff;
            }
        }
    }
    out
}

/// Compute B*G^T while ignoring output columns not present in `mask`.
/// This is the v0.6 practical support-restricted multiplication path.
pub fn right_recovery_sketch_masked(
    b: &CsrMatrix,
    g: &BinaryRecoveryMatrix,
    mask: &[bool],
) -> DenseMatrix {
    assert_eq!(g.domain(), b.cols);
    assert_eq!(mask.len(), b.cols);
    if g.is_identity() {
        let mut out = DenseMatrix::zeros(b.rows, b.cols);
        for k in 0..b.rows {
            for (j, value) in b.row(k) {
                if mask[j] {
                    out[(k, j)] = value;
                }
            }
        }
        return out;
    }

    let mut out = DenseMatrix::zeros(b.rows, g.rows());
    let rows_by_column: Vec<Vec<(usize, i64)>> = (0..g.domain())
        .map(|j| g.weighted_rows_for_index(j))
        .collect();
    for k in 0..b.rows {
        for (j, value) in b.row(k) {
            if !mask[j] {
                continue;
            }
            for &(mr, coeff) in &rows_by_column[j] {
                out[(k, mr)] += value * coeff;
            }
        }
    }
    out
}

/// Safe scalar decoder. Always returns at most `capacity` coordinates.
pub fn safe_decode_scalar(
    h: &BinaryRecoveryMatrix,
    measurement: &[i64],
    capacity: usize,
) -> Vec<(usize, i64)> {
    assert_eq!(measurement.len(), h.rows());
    let capacity = capacity.min(h.domain());
    if capacity == 0 {
        return Vec::new();
    }

    match h {
        BinaryRecoveryMatrix::Identity { domain } => {
            let mut out = Vec::new();
            for (i, &v) in measurement.iter().take(*domain).enumerate() {
                if v != 0 {
                    out.push((i, v));
                }
            }
            if out.len() <= capacity { out } else { Vec::new() }
        }
        BinaryRecoveryMatrix::Signature(sig) => {
            expander_safe_decode_scalar(sig, measurement, capacity)
        }
        BinaryRecoveryMatrix::Moment(moment) => {
            moment_safe_decode_scalar(moment, measurement, capacity)
        }
        BinaryRecoveryMatrix::Guv(guv) => {
            expander_safe_decode_scalar(guv, measurement, capacity)
        }
    }
}

/// Safe outer decoder over the direct-product ring R^m. `measurement` is the
/// m x rows(G) matrix W, with every column interpreted as one ring element.
pub fn safe_decode_product(
    g: &BinaryRecoveryMatrix,
    measurement: &DenseMatrix,
    capacity: usize,
) -> Vec<(usize, Vec<i64>)> {
    assert_eq!(measurement.cols, g.rows());
    let capacity = capacity.min(g.domain());
    if capacity == 0 {
        return Vec::new();
    }

    match g {
        BinaryRecoveryMatrix::Identity { domain } => {
            let mut out = Vec::new();
            for j in 0..*domain {
                let col = dense_col(measurement, j);
                if !is_zero_vec(&col) {
                    out.push((j, col));
                }
            }
            if out.len() <= capacity { out } else { Vec::new() }
        }
        BinaryRecoveryMatrix::Signature(sig) => {
            expander_safe_decode_product(sig, measurement, capacity)
        }
        BinaryRecoveryMatrix::Moment(moment) => {
            moment_safe_decode_product(moment, measurement, capacity)
        }
        BinaryRecoveryMatrix::Guv(guv) => {
            expander_safe_decode_product(guv, measurement, capacity)
        }
    }
}

fn moment_safe_decode_scalar(
    moment: &MomentRecovery,
    measurement: &[i64],
    capacity: usize,
) -> Vec<(usize, i64)> {
    let original = measurement.to_vec();
    let mut residual = original.clone();
    let mut total: BTreeMap<usize, i64> = BTreeMap::new();

    for _ in 0..capacity.max(1) {
        let proposal = moment_reduce_scalar(moment, &residual);
        if proposal.is_empty() {
            break;
        }
        if total.len().saturating_add(proposal.len()) > capacity {
            return Vec::new();
        }
        for &(idx, value) in &proposal {
            add_scalar_entry(&mut total, idx, value);
        }
        let measured = measure_scalar_moment(moment, &proposal);
        for (x, y) in residual.iter_mut().zip(measured) {
            *x -= y;
        }
    }

    let out: Vec<(usize, i64)> = total.into_iter().filter(|&(_, v)| v != 0).collect();
    if out.len() > capacity || measure_scalar_moment(moment, &out) != original {
        return Vec::new();
    }
    out
}

fn moment_reduce_scalar(moment: &MomentRecovery, measurement: &[i64]) -> Vec<(usize, i64)> {
    let mut candidates: BTreeMap<usize, Option<i64>> = BTreeMap::new();
    for bucket in 0..moment.bucket_count {
        let base = bucket * 3;
        let s0 = measurement[base];
        let s1 = measurement[base + 1];
        let s2 = measurement[base + 2];
        let Some((idx, value)) = moment_singleton_scalar(moment, bucket, s0, s1, s2) else {
            continue;
        };
        match candidates.entry(idx) {
            std::collections::btree_map::Entry::Vacant(e) => {
                e.insert(Some(value));
            }
            std::collections::btree_map::Entry::Occupied(mut e) => {
                let conflict = match e.get().as_ref() {
                    Some(existing) => *existing != value,
                    None => false,
                };
                if conflict {
                    e.insert(None);
                }
            }
        }
    }
    candidates
        .into_iter()
        .filter_map(|(idx, value)| value.map(|v| (idx, v)))
        .collect()
}

fn moment_singleton_scalar(
    moment: &MomentRecovery,
    bucket: usize,
    s0: i64,
    s1: i64,
    s2: i64,
) -> Option<(usize, i64)> {
    if s0 == 0 || s1 % s0 != 0 {
        return None;
    }
    let code = s1 / s0;
    if code <= 0 || code as usize > moment.domain {
        return None;
    }
    if s2 != code * code * s0 {
        return None;
    }
    let idx = code as usize - 1;
    moment.neighbors(idx).contains(&bucket).then_some((idx, s0))
}

fn measure_scalar_moment(moment: &MomentRecovery, entries: &[(usize, i64)]) -> Vec<i64> {
    let mut out = vec![0i64; moment.rows()];
    for &(idx, value) in entries {
        for (row, coeff) in moment.weighted_rows_for_index(idx) {
            out[row] += coeff * value;
        }
    }
    out
}

fn moment_safe_decode_product(
    moment: &MomentRecovery,
    measurement: &DenseMatrix,
    capacity: usize,
) -> Vec<(usize, Vec<i64>)> {
    let original = measurement.clone();
    let mut residual = measurement.clone();
    let mut total: BTreeMap<usize, Vec<i64>> = BTreeMap::new();

    for _ in 0..capacity.max(1) {
        let proposal = moment_reduce_product(moment, &residual);
        if proposal.is_empty() {
            break;
        }
        if total.len().saturating_add(proposal.len()) > capacity {
            return Vec::new();
        }
        for (idx, value) in &proposal {
            add_product_entry(&mut total, *idx, value);
        }
        let measured = measure_product_moment(moment, residual.rows, &proposal);
        sub_assign_dense(&mut residual, &measured);
    }

    let out: Vec<(usize, Vec<i64>)> = total
        .into_iter()
        .filter(|(_, v)| !is_zero_vec(v))
        .collect();
    if out.len() > capacity || measure_product_moment(moment, original.rows, &out) != original {
        return Vec::new();
    }
    out
}

fn moment_reduce_product(
    moment: &MomentRecovery,
    measurement: &DenseMatrix,
) -> Vec<(usize, Vec<i64>)> {
    let mut candidates: BTreeMap<usize, Option<Vec<i64>>> = BTreeMap::new();
    for bucket in 0..moment.bucket_count {
        let base = bucket * 3;
        let s0 = dense_col(measurement, base);
        let s1 = dense_col(measurement, base + 1);
        let s2 = dense_col(measurement, base + 2);
        let Some((idx, value)) = moment_singleton_product(moment, bucket, &s0, &s1, &s2) else {
            continue;
        };
        match candidates.entry(idx) {
            std::collections::btree_map::Entry::Vacant(e) => {
                e.insert(Some(value));
            }
            std::collections::btree_map::Entry::Occupied(mut e) => {
                let conflict = match e.get().as_ref() {
                    Some(existing) => existing.as_slice() != value.as_slice(),
                    None => false,
                };
                if conflict {
                    e.insert(None);
                }
            }
        }
    }
    candidates
        .into_iter()
        .filter_map(|(idx, value)| value.map(|v| (idx, v)))
        .collect()
}

fn moment_singleton_product(
    moment: &MomentRecovery,
    bucket: usize,
    s0: &[i64],
    s1: &[i64],
    s2: &[i64],
) -> Option<(usize, Vec<i64>)> {
    let mut code: Option<i64> = None;
    for r in 0..s0.len() {
        if s0[r] == 0 {
            if s1[r] != 0 || s2[r] != 0 {
                return None;
            }
            continue;
        }
        if s1[r] % s0[r] != 0 {
            return None;
        }
        let c = s1[r] / s0[r];
        match code {
            None => code = Some(c),
            Some(prev) if prev == c => {}
            Some(_) => return None,
        }
    }
    let code = code?;
    if code <= 0 || code as usize > moment.domain {
        return None;
    }
    let code2 = code * code;
    for r in 0..s0.len() {
        if s1[r] != code * s0[r] || s2[r] != code2 * s0[r] {
            return None;
        }
    }
    let idx = code as usize - 1;
    moment
        .neighbors(idx)
        .contains(&bucket)
        .then_some((idx, s0.to_vec()))
}

fn measure_product_moment(
    moment: &MomentRecovery,
    value_dim: usize,
    entries: &[(usize, Vec<i64>)],
) -> DenseMatrix {
    let mut out = DenseMatrix::zeros(value_dim, moment.rows());
    for (idx, value) in entries {
        assert_eq!(value.len(), value_dim);
        for (row, coeff) in moment.weighted_rows_for_index(*idx) {
            for i in 0..value_dim {
                out[(i, row)] += coeff * value[i];
            }
        }
    }
    out
}

fn expander_safe_decode_scalar<E: ExpanderSignature>(
    sig: &E,
    measurement: &[i64],
    capacity: usize,
) -> Vec<(usize, i64)> {
    let original = measurement.to_vec();
    let mut residual = original.clone();
    let mut total: BTreeMap<usize, i64> = BTreeMap::new();
    let iterations = ceil_log2(capacity.saturating_mul(2)).max(1);

    for _ in 0..iterations {
        let proposal = reduce_scalar(sig, &residual);
        if proposal.len().saturating_mul(2) > capacity.saturating_mul(3) {
            return Vec::new();
        }
        if proposal.is_empty() {
            break;
        }

        for &(idx, value) in &proposal {
            add_scalar_entry(&mut total, idx, value);
        }
        let measured = measure_scalar_expander(sig, &proposal);
        for i in 0..residual.len() {
            residual[i] -= measured[i];
        }
    }

    let out: Vec<(usize, i64)> = total.into_iter().filter(|&(_, v)| v != 0).collect();
    if out.len() > capacity {
        return Vec::new();
    }
    if measure_scalar_expander(sig, &out) != original {
        return Vec::new();
    }
    out
}

fn reduce_scalar<E: ExpanderSignature>(sig: &E, measurement: &[i64]) -> Vec<(usize, i64)> {
    let mut counts: HashMap<(usize, i64), usize> = HashMap::new();

    for bucket in 0..sig.bucket_count() {
        let base = bucket * sig.bits();
        let block = &measurement[base..base + sig.bits()];
        let Some(value) = unique_nonzero_scalar(block) else {
            continue;
        };

        let mut code = 0usize;
        for (bit, &v) in block.iter().enumerate() {
            if v == value {
                code |= 1usize << bit;
            }
        }
        if code == 0 || code > sig.domain() {
            continue;
        }
        let index = code - 1;
        if !sig.neighbors(index).contains(&bucket) {
            continue;
        }
        *counts.entry((index, value)).or_insert(0) += 1;
    }

    choose_majority_scalar(counts, sig.degree())
}

fn expander_safe_decode_product<E: ExpanderSignature>(
    sig: &E,
    measurement: &DenseMatrix,
    capacity: usize,
) -> Vec<(usize, Vec<i64>)> {
    let original = measurement.clone();
    let mut residual = measurement.clone();
    let mut total: BTreeMap<usize, Vec<i64>> = BTreeMap::new();
    let iterations = ceil_log2(capacity.saturating_mul(2)).max(1);

    for _ in 0..iterations {
        let proposal = reduce_product(sig, &residual);
        if proposal.len().saturating_mul(2) > capacity.saturating_mul(3) {
            return Vec::new();
        }
        if proposal.is_empty() {
            break;
        }

        for (idx, value) in &proposal {
            add_product_entry(&mut total, *idx, value);
        }
        let measured = measure_product_expander(sig, residual.rows, &proposal);
        sub_assign_dense(&mut residual, &measured);
    }

    let out: Vec<(usize, Vec<i64>)> = total
        .into_iter()
        .filter(|(_, v)| !is_zero_vec(v))
        .collect();
    if out.len() > capacity {
        return Vec::new();
    }
    if measure_product_expander(sig, original.rows, &out) != original {
        return Vec::new();
    }
    out
}

fn reduce_product<E: ExpanderSignature>(
    sig: &E,
    measurement: &DenseMatrix,
) -> Vec<(usize, Vec<i64>)> {
    let mut counts: HashMap<(usize, Vec<i64>), usize> = HashMap::new();

    for bucket in 0..sig.bucket_count() {
        let base = bucket * sig.bits();
        let mut value: Option<Vec<i64>> = None;
        let mut valid = true;

        for bit in 0..sig.bits() {
            let col = dense_col(measurement, base + bit);
            if is_zero_vec(&col) {
                continue;
            }
            match &value {
                None => value = Some(col),
                Some(v) if v.as_slice() == col.as_slice() => {}
                Some(_) => {
                    valid = false;
                    break;
                }
            }
        }
        if !valid {
            continue;
        }
        let Some(value) = value else {
            continue;
        };

        let mut code = 0usize;
        for bit in 0..sig.bits() {
            if dense_col_eq(measurement, base + bit, &value) {
                code |= 1usize << bit;
            }
        }
        if code == 0 || code > sig.domain() {
            continue;
        }
        let index = code - 1;
        if !sig.neighbors(index).contains(&bucket) {
            continue;
        }
        *counts.entry((index, value)).or_insert(0) += 1;
    }

    choose_majority_product(counts, sig.degree())
}

fn choose_majority_scalar(
    counts: HashMap<(usize, i64), usize>,
    degree: usize,
) -> Vec<(usize, i64)> {
    let mut best: BTreeMap<usize, (i64, usize, bool)> = BTreeMap::new();
    for ((idx, value), count) in counts {
        if count * 2 <= degree {
            continue;
        }
        match best.get_mut(&idx) {
            None => {
                best.insert(idx, (value, count, false));
            }
            Some((best_value, best_count, tied)) => {
                if count > *best_count {
                    *best_value = value;
                    *best_count = count;
                    *tied = false;
                } else if count == *best_count && value != *best_value {
                    *tied = true;
                }
            }
        }
    }
    best.into_iter()
        .filter_map(|(idx, (value, _, tied))| (!tied).then_some((idx, value)))
        .collect()
}

fn choose_majority_product(
    counts: HashMap<(usize, Vec<i64>), usize>,
    degree: usize,
) -> Vec<(usize, Vec<i64>)> {
    let mut best: BTreeMap<usize, (Vec<i64>, usize, bool)> = BTreeMap::new();
    for ((idx, value), count) in counts {
        if count * 2 <= degree {
            continue;
        }
        match best.get_mut(&idx) {
            None => {
                best.insert(idx, (value, count, false));
            }
            Some((best_value, best_count, tied)) => {
                if count > *best_count {
                    *best_value = value;
                    *best_count = count;
                    *tied = false;
                } else if count == *best_count && value.as_slice() != best_value.as_slice() {
                    *tied = true;
                }
            }
        }
    }
    best.into_iter()
        .filter_map(|(idx, (value, _, tied))| (!tied).then_some((idx, value)))
        .collect()
}

fn measure_scalar_expander<E: ExpanderSignature>(sig: &E, entries: &[(usize, i64)]) -> Vec<i64> {
    let mut out = vec![0i64; sig.rows()];
    for &(idx, value) in entries {
        for row in sig.rows_for_index(idx) {
            out[row] += value;
        }
    }
    out
}

fn measure_product_expander<E: ExpanderSignature>(
    sig: &E,
    value_dim: usize,
    entries: &[(usize, Vec<i64>)],
) -> DenseMatrix {
    let mut out = DenseMatrix::zeros(value_dim, sig.rows());
    for (idx, value) in entries {
        assert_eq!(value.len(), value_dim);
        for mr in sig.rows_for_index(*idx) {
            for i in 0..value_dim {
                out[(i, mr)] += value[i];
            }
        }
    }
    out
}

fn unique_nonzero_scalar(block: &[i64]) -> Option<i64> {
    let mut value = None;
    for &v in block {
        if v == 0 {
            continue;
        }
        match value {
            None => value = Some(v),
            Some(x) if x == v => {}
            Some(_) => return None,
        }
    }
    value
}

fn dense_col(m: &DenseMatrix, col: usize) -> Vec<i64> {
    (0..m.rows).map(|r| m[(r, col)]).collect()
}

fn dense_col_eq(m: &DenseMatrix, col: usize, value: &[i64]) -> bool {
    value.len() == m.rows && (0..m.rows).all(|r| m[(r, col)] == value[r])
}

fn is_zero_vec(v: &[i64]) -> bool {
    v.iter().all(|&x| x == 0)
}

fn add_scalar_entry(map: &mut BTreeMap<usize, i64>, idx: usize, value: i64) {
    let new = map.get(&idx).copied().unwrap_or(0) + value;
    if new == 0 {
        map.remove(&idx);
    } else {
        map.insert(idx, new);
    }
}

fn add_product_entry(map: &mut BTreeMap<usize, Vec<i64>>, idx: usize, value: &[i64]) {
    if let Some(current) = map.get_mut(&idx) {
        assert_eq!(current.len(), value.len());
        for i in 0..current.len() {
            current[i] += value[i];
        }
        let remove = is_zero_vec(current);
        if remove {
            // NLL releases `current` before this second mutable borrow.
            map.remove(&idx);
        }
    } else if !is_zero_vec(value) {
        map.insert(idx, value.to_vec());
    }
}

fn sub_assign_dense(lhs: &mut DenseMatrix, rhs: &DenseMatrix) {
    assert_eq!(lhs.rows, rhs.rows);
    assert_eq!(lhs.cols, rhs.cols);
    for (x, y) in lhs.data.iter_mut().zip(&rhs.data) {
        *x -= *y;
    }
}

#[derive(Clone, Debug)]
struct SparseColumns {
    rows: usize,
    cols: usize,
    data: Vec<BTreeMap<usize, i64>>,
}

impl SparseColumns {
    fn zeros(rows: usize, cols: usize) -> Self {
        Self {
            rows,
            cols,
            data: (0..cols).map(|_| BTreeMap::new()).collect(),
        }
    }

    fn nnz(&self) -> usize {
        self.data.iter().map(BTreeMap::len).sum()
    }

    fn add_to_column(&mut self, col: usize, entries: &[(usize, i64)]) -> bool {
        assert!(col < self.cols);
        let mut changed = false;
        for &(row, value) in entries {
            assert!(row < self.rows);
            if value == 0 {
                continue;
            }
            let current = self.data[col].get(&row).copied().unwrap_or(0);
            let new = current + value;
            if new != current {
                changed = true;
            }
            if new == 0 {
                self.data[col].remove(&row);
            } else {
                self.data[col].insert(row, new);
            }
        }
        changed
    }

    fn two_sided_measure(
        &self,
        h: &BinaryRecoveryMatrix,
        g: &BinaryRecoveryMatrix,
    ) -> DenseMatrix {
        assert_eq!(h.domain(), self.rows);
        assert_eq!(g.domain(), self.cols);
        let mut out = DenseMatrix::zeros(h.rows(), g.rows());

        for j in 0..self.cols {
            if self.data[j].is_empty() {
                continue;
            }
            let grows = g.weighted_rows_for_index(j);
            for (&i, &value) in &self.data[j] {
                let hrows = h.weighted_rows_for_index(i);
                for &(hr, hc) in &hrows {
                    for &(gr, gc) in &grows {
                        out[(hr, gr)] += hc * value * gc;
                    }
                }
            }
        }
        out
    }

    fn two_sided_measure_masked(
        &self,
        h: &BinaryRecoveryMatrix,
        g: &BinaryRecoveryMatrix,
        mask: &[bool],
    ) -> DenseMatrix {
        assert_eq!(mask.len(), self.cols);
        assert_eq!(h.domain(), self.rows);
        assert_eq!(g.domain(), self.cols);
        let mut out = DenseMatrix::zeros(h.rows(), g.rows());
        for j in 0..self.cols {
            if !mask[j] || self.data[j].is_empty() {
                continue;
            }
            let grows = g.weighted_rows_for_index(j);
            for (&i, &value) in &self.data[j] {
                let hrows = h.weighted_rows_for_index(i);
                for &(hr, hc) in &hrows {
                    for &(gr, gc) in &grows {
                        out[(hr, gr)] += hc * value * gc;
                    }
                }
            }
        }
        out
    }

    fn to_csr(&self) -> CsrMatrix {
        let mut triplets = Vec::with_capacity(self.nnz());
        for j in 0..self.cols {
            for (&i, &v) in &self.data[j] {
                if v != 0 {
                    triplets.push((i, j, v));
                }
            }
        }
        CsrMatrix::from_triplets(self.rows, self.cols, &triplets)
    }
}

fn hashed_neighbors(seed: u64, bucket_count: usize, degree: usize, index: usize) -> Vec<usize> {
    let mut out = Vec::with_capacity(degree);
    let mut attempt = 0u64;
    while out.len() < degree {
        let key = seed
            ^ (index as u64).wrapping_mul(0x9E37_79B9_7F4A_7C15)
            ^ attempt.wrapping_mul(0xD1B5_4A32_D192_ED03);
        let b = (splitmix64(key) % bucket_count as u64) as usize;
        if !out.contains(&b) {
            out.push(b);
        }
        attempt = attempt.wrapping_add(1);
    }
    out
}

#[inline]
fn splitmix64(mut x: u64) -> u64 {
    x = x.wrapping_add(0x9E37_79B9_7F4A_7C15);
    x = (x ^ (x >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    x = (x ^ (x >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    x ^ (x >> 31)
}

fn ceil_log2(x: usize) -> usize {
    if x <= 1 {
        0
    } else {
        usize::BITS as usize - (x - 1).leading_zeros() as usize
    }
}

