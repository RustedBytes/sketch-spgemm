/// Practical deterministic compressed-recovery configuration.
///
/// This implements the *shape* of Bennett et al.'s A \otimes_r B recovery
/// matrix: a left-regular bucket graph A whose rows are augmented with the
/// binary index-signature matrix B. The bucket graph here is generated by a
/// deterministic SplitMix hash family, not the explicit GUV expander used in
/// the theorem. Consequently this backend is an engineering/prototyping
/// backend, not a proof-level implementation of Theorem 2.4 in Graia (2026).
#[derive(Clone, Debug)]
pub struct SignatureConfig {
    /// Number of bucket neighbors per logical input coordinate.
    pub degree: usize,
    /// Base bucket count is ceil(oversampling * capacity), capped at domain.
    pub oversampling: f64,
    /// Deterministic seed used to construct the bucket graph.
    pub seed: u64,
    /// If the signature measurement would use at least as many rows as I_N,
    /// use the identity recovery pair instead.
    pub identity_fallback: bool,
    /// Run one final I_r / I_c residual correction pass. This makes the
    /// practical signature backend return an exact product even if its hashed
    /// graph has a sparse-recovery collision. It is intentionally expensive
    /// and should be disabled when benchmarking compressed recovery itself.
    pub guaranteed_correction: bool,
}

impl Default for SignatureConfig {
    fn default() -> Self {
        Self {
            degree: 5,
            oversampling: 2.0,
            seed: 0x5A17_9EED_D15C_A11E,
            identity_fallback: true,
            guaranteed_correction: true,
        }
    }
}

/// Practical moment/IBLT-style sparse-recovery configuration.
///
/// Each bucket uses three algebraic measurements instead of a binary
/// index-signature block: S0=sum(x_i), S1=sum((i+1)x_i), and
/// S2=sum((i+1)^2 x_i). Singleton buckets therefore reveal both the index and
/// value, while the quadratic moment rejects most collisions. This backend is
/// intentionally an engineering backend over exact i64 arithmetic, not the
/// arbitrary-ring recovery pair from the theorem.
#[derive(Clone, Debug)]
pub struct MomentConfig {
    pub degree: usize,
    pub oversampling: f64,
    pub seed: u64,
    pub identity_fallback: bool,
    pub guaranteed_correction: bool,
}

impl Default for MomentConfig {
    fn default() -> Self {
        Self {
            degree: 3,
            oversampling: 3.0,
            seed: 0x4D4F_4D45_4E54_0001,
            identity_fallback: true,
            guaranteed_correction: true,
        }
    }
}

#[derive(Clone, Debug)]
pub enum RecoveryBackend {
    /// Exact recovery using identity matrices. This follows Algorithm 1
    /// literally but does not compress the two-sided measurements.
    Identity,
    /// Practical A \otimes_r B signature recovery with deterministic hashing.
    Signature(SignatureConfig),
    /// Practical three-moment / IBLT-style peeling recovery.
    Moment(MomentConfig),
    /// Proof-oriented A \otimes_r B recovery using the explicit
    /// Guruswami-Umans-Vadhan / Parvaresh-Vardy unbalanced expander.
    Guv(GuvConfig),
}

#[derive(Clone, Debug)]
pub enum BinaryRecoveryMatrix {
    Identity { domain: usize },
    Signature(SignatureRecovery),
    Moment(MomentRecovery),
    Guv(GuvRecovery),
}

#[derive(Clone, Debug, PartialEq, Eq, Hash)]
enum RecoveryMatrixKey {
    Identity { domain: usize },
    Signature {
        domain: usize,
        capacity: usize,
        degree: usize,
        oversampling_bits: u64,
        seed: u64,
    },
    Moment {
        domain: usize,
        capacity: usize,
        degree: usize,
        oversampling_bits: u64,
        seed: u64,
    },
    Guv {
        domain: usize,
        capacity: usize,
        alpha_bits: u64,
        epsilon_bits: u64,
    },
}

impl RecoveryMatrixKey {
    #[inline]
    fn cacheable(&self) -> bool {
        // Signature matrices are deliberately reseeded every round. A signature
        // request that falls back to identity receives an Identity key and is
        // therefore cacheable.
        !matches!(self, Self::Signature { .. } | Self::Moment { .. })
    }
}

#[derive(Clone)]
struct CachedProduct {
    matrix: Arc<DenseMatrix>,
    stats: RectangularStats,
}

#[derive(Clone, Debug, PartialEq, Eq, Hash)]
struct ResidualCacheKey {
    h: RecoveryMatrixKey,
    g: RecoveryMatrixKey,
    d_version: u64,
}

#[derive(Clone)]
struct CachedResidual {
    matrix: Arc<DenseMatrix>,
    product_stats: RectangularStats,
}

impl BinaryRecoveryMatrix {
    pub fn identity(domain: usize) -> Self {
        Self::Identity { domain }
    }

    pub fn domain(&self) -> usize {
        match self {
            Self::Identity { domain } => *domain,
            Self::Signature(s) => s.domain,
            Self::Moment(m) => m.domain,
            Self::Guv(g) => g.domain,
        }
    }

    pub fn rows(&self) -> usize {
        match self {
            Self::Identity { domain } => *domain,
            Self::Signature(s) => s.rows(),
            Self::Moment(m) => m.rows(),
            Self::Guv(g) => g.rows(),
        }
    }

    pub fn kind(&self) -> &'static str {
        match self {
            Self::Identity { .. } => "identity",
            Self::Signature(_) => "signature-hash",
            Self::Moment(_) => "moment-hash",
            Self::Guv(_) => "guv-expander",
        }
    }

    #[inline]
    pub fn is_identity(&self) -> bool {
        matches!(self, Self::Identity { .. })
    }

    /// Enumerate row positions containing a 1 in one logical column.
    #[inline]
    pub fn rows_for_index(&self, index: usize) -> Vec<usize> {
        assert!(index < self.domain());
        match self {
            Self::Identity { .. } => vec![index],
            Self::Signature(s) => s.rows_for_index(index),
            Self::Moment(m) => m.rows_for_index(index),
            Self::Guv(g) => g.rows_for_index(index),
        }
    }

    /// Enumerate nonzero measurement coefficients in one logical column.
    /// Binary backends return coefficient 1; the moment backend returns the
    /// three moment coefficients for every bucket neighbor.
    #[inline]
    pub fn weighted_rows_for_index(&self, index: usize) -> Vec<(usize, i64)> {
        assert!(index < self.domain());
        match self {
            Self::Identity { .. } => vec![(index, 1)],
            Self::Signature(s) => s.rows_for_index(index).into_iter().map(|r| (r, 1)).collect(),
            Self::Moment(m) => m.weighted_rows_for_index(index),
            Self::Guv(g) => g.rows_for_index(index).into_iter().map(|r| (r, 1)).collect(),
        }
    }
}

/// Binary index-signature recovery matrix H = A \otimes_r B.
///
/// A is an implicit left-regular bucket graph. B contains the non-zero binary
/// code of `index + 1`, so index 0 is distinguishable from the zero vector.
#[derive(Clone, Debug)]
pub struct SignatureRecovery {
    pub domain: usize,
    pub capacity: usize,
    pub bucket_count: usize,
    pub degree: usize,
    pub bits: usize,
    pub seed: u64,
}

impl SignatureRecovery {
    pub fn new(
        domain: usize,
        capacity: usize,
        degree: usize,
        oversampling: f64,
        seed: u64,
    ) -> Self {
        assert!(domain > 0);
        assert!(capacity > 0 && capacity <= domain);
        assert!(degree > 0);
        assert!(oversampling.is_finite() && oversampling > 0.0);

        let bucket_count = (((capacity as f64) * oversampling).ceil() as usize)
            .max(degree)
            .min(domain.max(1));
        let degree = degree.min(bucket_count);
        let bits = ceil_log2(domain.saturating_add(1)).max(1);

        Self {
            domain,
            capacity,
            bucket_count,
            degree,
            bits,
            seed,
        }
    }

    #[inline]
    pub fn rows(&self) -> usize {
        self.bucket_count.saturating_mul(self.bits)
    }

    #[inline]
    pub fn neighbors(&self, index: usize) -> Vec<usize> {
        assert!(index < self.domain);
        hashed_neighbors(self.seed, self.bucket_count, self.degree, index)
    }

    #[inline]
    pub fn rows_for_index(&self, index: usize) -> Vec<usize> {
        let code = index + 1;
        let neighbors = self.neighbors(index);
        let mut out = Vec::with_capacity(self.degree * self.bits);
        for bucket in neighbors {
            let base = bucket * self.bits;
            for bit in 0..self.bits {
                if ((code >> bit) & 1) != 0 {
                    out.push(base + bit);
                }
            }
        }
        out
    }
}

/// Three-moment left-regular recovery matrix. Each bucket owns rows
/// [3b, 3b+1, 3b+2] with coefficients 1, code, code^2, where code=index+1.
#[derive(Clone, Debug)]
pub struct MomentRecovery {
    pub domain: usize,
    pub capacity: usize,
    pub bucket_count: usize,
    pub degree: usize,
    pub seed: u64,
}

impl MomentRecovery {
    pub fn new(
        domain: usize,
        capacity: usize,
        degree: usize,
        oversampling: f64,
        seed: u64,
    ) -> Self {
        assert!(domain > 0);
        assert!(capacity > 0 && capacity <= domain);
        assert!(degree > 0);
        assert!(oversampling.is_finite() && oversampling > 0.0);
        let bucket_count = (((capacity as f64) * oversampling).ceil() as usize)
            .max(degree)
            .min(domain.max(1));
        let degree = degree.min(bucket_count);
        Self { domain, capacity, bucket_count, degree, seed }
    }

    #[inline]
    pub fn rows(&self) -> usize {
        self.bucket_count.saturating_mul(3)
    }

    #[inline]
    pub fn neighbors(&self, index: usize) -> Vec<usize> {
        assert!(index < self.domain);
        hashed_neighbors(self.seed, self.bucket_count, self.degree, index)
    }

    #[inline]
    pub fn rows_for_index(&self, index: usize) -> Vec<usize> {
        let mut out = Vec::with_capacity(self.degree * 3);
        for bucket in self.neighbors(index) {
            let base = bucket * 3;
            out.extend_from_slice(&[base, base + 1, base + 2]);
        }
        out
    }

    #[inline]
    pub fn weighted_rows_for_index(&self, index: usize) -> Vec<(usize, i64)> {
        let code = (index + 1) as i64;
        let code2 = code.saturating_mul(code);
        let mut out = Vec::with_capacity(self.degree * 3);
        for bucket in self.neighbors(index) {
            let base = bucket * 3;
            out.push((base, 1));
            out.push((base + 1, code));
            out.push((base + 2, code2));
        }
        out
    }
}

/// Common interface needed by Bennett et al.'s Reduce/Recovery decoder.
/// Both the hash prototype and the explicit GUV graph are augmented with the
/// same binary index-signature matrix B, so the decoder is graph-agnostic.
trait ExpanderSignature {
    fn domain(&self) -> usize;
    fn bucket_count(&self) -> usize;
    fn degree(&self) -> usize;
    fn bits(&self) -> usize;
    fn neighbors(&self, index: usize) -> Vec<usize>;
    fn rows_for_index(&self, index: usize) -> Vec<usize>;
    fn rows(&self) -> usize;
}

impl ExpanderSignature for SignatureRecovery {
    fn domain(&self) -> usize { self.domain }
    fn bucket_count(&self) -> usize { self.bucket_count }
    fn degree(&self) -> usize { self.degree }
    fn bits(&self) -> usize { self.bits }
    fn neighbors(&self, index: usize) -> Vec<usize> { SignatureRecovery::neighbors(self, index) }
    fn rows_for_index(&self, index: usize) -> Vec<usize> { SignatureRecovery::rows_for_index(self, index) }
    fn rows(&self) -> usize { SignatureRecovery::rows(self) }
}

impl ExpanderSignature for GuvRecovery {
    fn domain(&self) -> usize { self.domain }
    fn bucket_count(&self) -> usize { self.bucket_count }
    fn degree(&self) -> usize { self.degree }
    fn bits(&self) -> usize { self.bits }
    fn neighbors(&self, index: usize) -> Vec<usize> { GuvRecovery::neighbors(self, index) }
    fn rows_for_index(&self, index: usize) -> Vec<usize> { GuvRecovery::rows_for_index(self, index) }
    fn rows(&self) -> usize { GuvRecovery::rows(self) }
}

#[derive(Clone, Debug)]
pub struct NestedOptions {
    pub rectangular_policy: RectangularPolicy,
    /// Engineering scheduler: after an identity outer measurement exposes the
    /// number of live residual columns, skip q-levels below the next power of
    /// two of K_remaining / live_columns.
    pub practical_scheduler: bool,
    /// Optional output-nnz estimate used only by the practical q scheduler.
    /// This lets AutoSpGEMM keep a conservative K bound while scheduling from
    /// a tighter sampled estimate.
    pub scheduler_k_hint: Option<usize>,
    /// Engineering support mask: after identity outer recovery exposes concrete
    /// column ids, restrict later B/G work to those observed residual columns.
    pub masked_residual: bool,
    /// Marks k_bound as the exact nnz(C), rather than merely an upper bound.
    /// Used only for practical support-completeness checks/safety fallback.
    pub exact_k_bound: bool,
    /// Optional independent bilinear residual certificate. When enabled, an
    /// exhausted support mask can be accepted without knowing exact K.
    pub residual_fingerprint: Option<FingerprintConfig>,
    /// If a fingerprint-enabled run reaches the end without a valid residual
    /// certificate, append an exact correction pass. AutoSpGEMM normally keeps
    /// this false and performs an explicit exact fallback at the wrapper level.
    pub fingerprint_failure_correction: bool,
}

impl Default for NestedOptions {
    fn default() -> Self {
        Self {
            rectangular_policy: RectangularPolicy::Auto,
            practical_scheduler: false,
            scheduler_k_hint: None,
            masked_residual: false,
            exact_k_bound: false,
            residual_fingerprint: None,
            fingerprint_failure_correction: false,
        }
    }
}

